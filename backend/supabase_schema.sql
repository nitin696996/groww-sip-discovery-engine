-- Supabase SQL Schema for Groww 4-Stage SIP Behavioral Pipeline
-- Run this in your Supabase SQL Editor. Credentials remain strictly on the backend via SUPABASE_SERVICE_ROLE_KEY.

CREATE TABLE IF NOT EXISTS public.sip_pipeline_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_hash TEXT NOT NULL UNIQUE,
    external_id TEXT NOT NULL,
    source TEXT NOT NULL,
    sub_source TEXT DEFAULT '',
    author_handle TEXT DEFAULT 'anonymous',
    title TEXT DEFAULT '',
    content TEXT NOT NULL,
    url TEXT DEFAULT '',
    rating INTEGER DEFAULT NULL,
    upvotes INTEGER DEFAULT 0,
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Stage 2: Contextual Enrichment & Cleaning
    triage_score DOUBLE PRECISION DEFAULT 0.0,
    triage_status TEXT DEFAULT 'CLEAN_SIP_SIGNAL', -- HIGH_SIGNAL / LOW_SIGNAL_NOISE
    cleaning_status TEXT DEFAULT 'CLEAN_SIP_SIGNAL', -- CLEAN_SIP_SIGNAL, FILTERED_SPAM_PROMO, FILTERED_NON_SIP
    cleaning_reason TEXT DEFAULT '',

    -- Stage 3: LLM Semantic Tagging & Clustering
    processed_by_llm BOOLEAN DEFAULT FALSE,
    behavioral_trigger TEXT DEFAULT '',
    sentiment_polarity DOUBLE PRECISION DEFAULT 0.0,
    sentiment_label TEXT DEFAULT '',
    emotional_intensity DOUBLE PRECISION DEFAULT 0.0,
    segment_proxy_ticket TEXT DEFAULT '',
    segment_proxy_tenure TEXT DEFAULT '',

    -- Stage 4: Opportunity Area Scoring & Retention Drop-Off Correlation
    retention_dropoff_bucket TEXT DEFAULT '', -- Months 1-3, Months 6-8, Months 10-12
    opportunity_score INTEGER DEFAULT 0,
    recommended_action TEXT DEFAULT '',
    verbatim_quote TEXT DEFAULT '',
    extracted_by_provider TEXT DEFAULT '',
    analyzed_at TIMESTAMPTZ DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_sip_pipeline_cleaning ON public.sip_pipeline_rows (cleaning_status);
CREATE INDEX IF NOT EXISTS idx_sip_pipeline_trigger ON public.sip_pipeline_rows (behavioral_trigger);
CREATE INDEX IF NOT EXISTS idx_sip_pipeline_source ON public.sip_pipeline_rows (source);

-- Enable Row Level Security (RLS) so public/anon frontend keys cannot access or mutate data directly.
-- Only the FastAPI backend using SUPABASE_SERVICE_ROLE_KEY can read/write.
ALTER TABLE public.sip_pipeline_rows ENABLE ROW LEVEL SECURITY;
